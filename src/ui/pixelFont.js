const SETS = { small: SMALL, big: BIG };

/** Width in font pixels of `text` (letters plus a 1-pixel gap between them). */
export function textWidth(text, set = 'small') {
  const font = SETS[set];
  let w = 0;
  for (const ch of text.toUpperCase()) w += ((font[ch] || font[' '])[0].length) + 1;
  return Math.max(0, w - 1);
}

/** Height in font pixels of one line in this set. */
export const textHeight = (set = 'small') => (set === 'big' ? 9 : 7);

/**
 * Draw `text` with its top-left corner at (x, y).
 * @param {CanvasRenderingContext2D} g
 * @param {number} scale   how many canvas pixels per font pixel
 * @param {number} slant   italic lean: canvas pixels to shift right per canvas row from the bottom
 */
export function drawPixelText(g, text, x, y, { set = 'small', scale = 1, slant = 0 } = {}) {
  const font = SETS[set];
  const rows = textHeight(set);
  const height = rows * scale;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = font[ch] || font[' '];
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < glyph[r].length; c++) {
        if (glyph[r][c] !== '#') continue;
        // Each font pixel is a scale×scale block, drawn one canvas row at a
        // time so the italic lean steps smoothly down the letter.
        for (let k = 0; k < scale; k++) {
          const py = r * scale + k;
          const lean = Math.round((height - 1 - py) * slant);
          g.fillRect(cx + c * scale + lean, y + py, scale, 1);
        }
      }
    }
    cx += (glyph[0].length + 1) * scale;
  }
}
